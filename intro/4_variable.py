# naming rules untuk variabel di Python:
# 1. Nama variabel harus dimulai dengan huruf atau garis bawah (_).
# 2. Nama variabel hanya boleh mengandung huruf, angka, dan garis bawah
# 3. Nama variabel tidak boleh menggunakan kata kunci yang sudah ada di Python (misalnya: if, else, while, for, def, class, dll)
# 4. Nama variabel bersifat case-sensitive, artinya nama variabel "age" dan "Age" adalah dua variabel yang berbeda.

